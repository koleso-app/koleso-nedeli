// Copies the Cyrillic + Latin font files from @fontsource into app/fonts and writes app/fonts/fonts.css,
// so the app works offline and the phone version does not depend on any font CDN.
// Run: node scripts/copy-fonts.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const out = path.join(root, "app", "fonts");
const FACES = [["onest", [400, 500, 600, 700]], ["prata", [400]], ["jetbrains-mono", [500, 700]]];
const SUBSETS = ["cyrillic", "latin"];

fs.mkdirSync(out, { recursive: true });
let css = "/* generated by scripts/copy-fonts.js from @fontsource (SIL Open Font License) */\n";
for (const [pkg, weights] of FACES) {
  const dir = path.join(root, "node_modules", "@fontsource", pkg);
  for (const w of weights) {
    const src = fs.readFileSync(path.join(dir, `${w}.css`), "utf8");
    for (const block of src.split(/\n(?=\/\*)/)) {
      const name = (block.match(/\/\* (.+?) \*\//) || [])[1] || "";
      if (!SUBSETS.some(s => name === `${pkg}-${s}-${w}-normal`)) continue;
      const file = `${name}.woff2`;
      fs.copyFileSync(path.join(dir, "files", file), path.join(out, file));
      css += block.replace(/src:[^;]+;/, `src: url(./${file}) format('woff2');`).trim() + "\n\n";
    }
  }
}
fs.writeFileSync(path.join(out, "fonts.css"), css);
const lic = path.join(root, "node_modules", "@fontsource", "onest", "LICENSE");
if (fs.existsSync(lic)) fs.copyFileSync(lic, path.join(out, "LICENSE-OFL.txt"));
console.log("fonts:", fs.readdirSync(out).length, "files");
